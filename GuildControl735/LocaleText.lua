-- SavedVariables are read at ADDON_LOADED, before any addon UI is created.
GC.localeTables={}
local function update(target,source)
 for key,value in pairs(source)do
  if type(value)=='table'then
   if type(target[key])~='table'then target[key]={}end
   update(target[key],value)
  else target[key]=value end
 end
 return target
end
function GC:RegisterLocaleTable(target,factory)
 self.localeTables[#self.localeTables+1]={target=target,factory=factory}
 return update(target,factory())
end
GC:RegisterLocaleTable(GC.L,function()return GC.LocaleMainDicts[GC.locale]end)
function GC:InitializeLanguage(db)
 local mode=type(db)=='table'and db.interfaceLanguage
 self.languageMode=(mode=='en'or mode=='ru')and mode or'auto'
 self.clientLocale=GetLocale()=='ruRU'and'ruRU'or'enUS'
 self.locale=self.languageMode=='en'and'enUS'or self.languageMode=='ru'and'ruRU'or self.clientLocale
 for _,entry in ipairs(self.localeTables)do update(entry.target,entry.factory())end
end
function GC:LanguageCommand(value)
 value=(value or''):lower()
 local db=self.accountDB or self.db
 if value==''then
  self:Print('Language: '..(self.languageMode or'auto')..' / '..tostring(self.locale)..'. /gc735 language en | ru | auto')
  return true
 end
 if value~='en'and value~='ru'and value~='auto'then
  self:Print('/gc735 language en | ru | auto');return false
 end
 if type(db)~='table'then self:Print('Settings unavailable / Настройки недоступны.');return false end
 if value=='auto'then db.interfaceLanguage=nil else db.interfaceLanguage=value end
 self:Print('Language: '..value..'. Use /reload to apply. / Выполните /reload для применения.')
 return true
end

